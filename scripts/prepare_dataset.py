from __future__ import annotations

import argparse
import json
from pathlib import Path
import shutil

from src.data.adapters.nwpu import discover_nwpu_items
from src.data.audit import audit_dataset
from src.data.manifests import load_split_manifest
from src.data.parsers.nwpu import parse_nwpu_annotation
from src.data.splitting import SplitConfig, create_dataset_splits, save_split_manifest
from src.data.yolo import export_yolo_dataset, validate_yolo_dataset
from src.detection.config import load_detection_config, resolve_path
from src.utils.archive import extract_zip
from src.utils.paths import find_project_root


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Audit, split, and export NWPU VHR-10 for detector training."
    )
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument(
        "--force",
        action="store_true",
        help="Replace the configured manifest/export generated by this command.",
    )
    return parser.parse_args()


def _check_expected(report: dict, audit_config: dict) -> None:
    fields = {
        "total_images": "expected_images",
        "total_objects": "expected_objects",
        "background_images": "expected_backgrounds",
    }
    for report_key, config_key in fields.items():
        expected = audit_config.get(config_key)
        if expected is not None and report[report_key] != expected:
            raise ValueError(
                f"Audit expected {expected} for {report_key}, "
                f"found {report[report_key]}"
            )


def _clear_export(output_root: Path) -> None:
    output_root = output_root.resolve()
    if output_root.parent == output_root or not output_root.name:
        raise ValueError(f"Refusing to remove unsafe output path: {output_root}")
    shutil.rmtree(output_root)


def main() -> None:
    args = parse_args()
    project_root = find_project_root(Path(__file__).resolve())
    config = load_detection_config(args.config)
    raw_root = resolve_path(config["data"]["raw_root"], project_root)
    archive_path = resolve_path(config["data"]["archive_path"], project_root)

    try:
        items = discover_nwpu_items(raw_root)
    except FileNotFoundError:
        extract_zip(archive_path, raw_root)
        items = discover_nwpu_items(raw_root)

    audit_config = config["data"]["audit"]
    if audit_config["enabled"]:
        audit_path = resolve_path(audit_config["report_path"], project_root)
        if (
            audit_config.get("reuse_report", False)
            and audit_path.is_file()
            and not args.force
        ):
            audit_report = json.loads(audit_path.read_text(encoding="utf-8"))
            print(f"Reused dataset audit: {audit_path}")
        else:
            audit_report = audit_dataset(
                items, parse_nwpu_annotation, set(range(1, 11))
            )
            audit_path.parent.mkdir(parents=True, exist_ok=True)
            audit_path.write_text(
                json.dumps(audit_report, indent=2) + "\n", encoding="utf-8"
            )
            print(f"Saved dataset audit: {audit_path}")
        _check_expected(audit_report, audit_config)
        if audit_config["fail_on_issues"] and audit_report["issues"]:
            raise ValueError(
                f"Dataset audit found {len(audit_report['issues'])} issues. "
                f"See {audit_path}"
            )

    split_section = config["split"]
    split_config = SplitConfig(
        train_ratio=split_section["train"],
        val_ratio=split_section["val"],
        test_ratio=split_section["test"],
        seed=config["experiment"]["seed"],
    )
    manifest_path = resolve_path(split_section["manifest_path"], project_root)
    if manifest_path.is_file() and split_section["reuse_manifest"] and not args.force:
        splits = load_split_manifest(manifest_path, raw_root)
        print(f"Reused split manifest: {manifest_path}")
    else:
        splits = create_dataset_splits(items, split_config)
        save_split_manifest(
            splits,
            manifest_path,
            raw_root,
            split_config,
            overwrite=args.force,
        )
        print(f"Saved split manifest: {manifest_path}")

    export_config = config["export"]
    output_root = resolve_path(export_config["output_root"], project_root)
    if output_root.exists() and any(output_root.iterdir()):
        if args.force:
            _clear_export(output_root)
        else:
            validation = validate_yolo_dataset(
                output_root,
                export_config.get("expected_images"),
                export_config.get("expected_objects"),
                export_config.get("expected_backgrounds"),
            )
            print(f"Reused validated YOLO export: {output_root}")
            print(json.dumps(validation, indent=2))
            return

    export_yolo_dataset(splits, output_root, config["classes"])
    validation = validate_yolo_dataset(
        output_root,
        export_config.get("expected_images"),
        export_config.get("expected_objects"),
        export_config.get("expected_backgrounds"),
    )
    print(f"Prepared YOLO dataset: {output_root}")
    print(json.dumps(validation, indent=2))


if __name__ == "__main__":
    main()
